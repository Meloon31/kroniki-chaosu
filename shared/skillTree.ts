export function getSkillRankEffectiveStats(skill: TreeSkillDef, rawRank: number) {
  const rank = Math.max(1, Math.min(MAX_TREE_SKILL_OVERCAP_RANK, rawRank));
  // Ranks 1..10 grow steadily; Chaos Overcap +11 and +12 give a huge power leap!
  let powerMult = 1 + (Math.min(10, rank) - 1) * (skill.powerPctPerRank / 100);
  if (rank === 11) powerMult += 0.22;
  if (rank >= 12) powerMult += 0.5;
  const effectiveCooldown = Number(
    Math.max(skill.cooldown * 0.55, skill.cooldown - (rank - 1) * skill.cdReductionPerRank).toFixed(2)
  );
  const effectiveRadius = Number((skill.radius * (1 + (rank - 1) * 0.025)).toFixed(2));
  const effectiveDuration = skill.durationSec
    ? Number((skill.durationSec + (rank - 1) * 0.15).toFixed(2))
    : 0;
  return {
    rank,
    powerMult: Number(powerMult.toFixed(3)),
    powerBonusPct: Math.round((powerMult - 1) * 100),
    effectiveCooldown,
    effectiveRadius,
    effectiveDuration,
  };
}

export function createDefaultSkillTree(classId: ClassId): {
  skillTree: Record<string, SkillTreeNodeProgress>;
  equippedSkills: [string, string, string];
} {
  const tree = CLASS_SKILL_TREES[classId];
  const skillTree: Record<string, SkillTreeNodeProgress> = {};
  for (const sk of tree.skills) {
    const isStarter = tree.defaultEquipped.includes(sk.id);
    skillTree[sk.id] = {
      rank: isStarter ? 1 : 0,
      corrupted: false,
      chaosModId: null,
    };
  }
  return {
    skillTree,
    equippedSkills: [...tree.defaultEquipped] as [string, string, string],
  };
}

export function ensureSkillTreeForClass(
  classId: ClassId,
  existingTree?: Record<string, SkillTreeNodeProgress>,
  existingEquipped?: [string, string, string]
): {
  skillTree: Record<string, SkillTreeNodeProgress>;
  equippedSkills: [string, string, string];
} {
  const def = createDefaultSkillTree(classId);
  const tree = CLASS_SKILL_TREES[classId];
  const merged: Record<string, SkillTreeNodeProgress> = {};
  for (const sk of tree.skills) {
    const prev = existingTree?.[sk.id];
    if (prev && typeof prev.rank === 'number') {
      merged[sk.id] = {
        rank: Math.max(0, Math.min(MAX_TREE_SKILL_OVERCAP_RANK, Math.floor(prev.rank))),
        corrupted: Boolean(prev.corrupted),
        chaosModId: prev.chaosModId ?? null,
      };
    } else {
      merged[sk.id] = { ...def.skillTree[sk.id] };
    }
  }

  // Ensure equipped 3 skills all belong to this class and have rank >= 1 (fallback to unlocked or starter)
  const validClassIds = new Set(tree.skills.map((s) => s.id));
  const outEquipped: [string, string, string] = [...def.equippedSkills];
  if (Array.isArray(existingEquipped) && existingEquipped.length === 3) {
    const used = new Set<string>();
    for (let i = 0; i < 3; i++) {
      const id = existingEquipped[i];
      if (id && validClassIds.has(id) && (merged[id]?.rank || 0) >= 1 && !used.has(id)) {
        outEquipped[i] = id;
        used.add(id);
      } else {
        const fallback =
          tree.skills.find((s) => (merged[s.id]?.rank || 0) >= 1 && !used.has(s.id))?.id ||
          def.equippedSkills[i];
        outEquipped[i] = fallback;
        used.add(fallback);
      }
    }
  }
  return { skillTree: merged, equippedSkills: outEquipped };
}

export function canUpgradeTreeSkill(
  profile: Pick<PlayerProfile, 'classId' | 'level' | 'skillPoints' | 'skillTree'>,
  skillId: string
): { ok: boolean; reason?: string } {
  const sk = ALL_TREE_SKILLS[skillId];
  if (!sk || sk.classId !== profile.classId) return { ok: false, reason: 'Nieprawidłowa umiejętność' };
  const node = profile.skillTree?.[skillId];
  const rank = node?.rank || 0;
  if (rank >= MAX_TREE_SKILL_RANK) return { ok: false, reason: 'Osiągnięto limit punktów (10/10 — użyj Kamienia Chaosu po +12!)' };
  if (profile.level < sk.reqLevel) return { ok: false, reason: `Wymaga poziomu postaci ${sk.reqLevel}` };
  for (const pid of sk.parentIds) {
    const pRank = profile.skillTree?.[pid]?.rank || 0;
    if (pRank < 1) {
      const pName = ALL_TREE_SKILLS[pid]?.name || pid;
      return { ok: false, reason: `Wymaga min. 1 pkt w: ${pName}` };
    }
  }
  if ((profile.skillPoints || 0) < 1) return { ok: false, reason: 'Brak Punktów Umiejętności' };
  return { ok: true };
}

export type SkillChaosOutcomeKind =
  | 'new_modifier'
  | 'overcap_plus2'
  | 'reset_zero'
  | 'no_effect';

export interface SkillChaosCorruptionResult {
  outcome: SkillChaosOutcomeKind;
  skillId: string;
  previousRank: number;
  newRank: number;
  chaosModId?: SkillChaosModId | null;
  updatedProgress: SkillTreeNodeProgress;
  message: string;
}

/**
 * Permanent 1-time Chaos Stone Corruption on a Skill (exact 10% / 10% / 10% / 70% pool):
 * - 10% New Permanent Skill Modifier
 * - 10% +2 Overcap Breakthrough (only way to break past +10 to +12!)
 * - 10% Reset Skill to Rank 0 (invested points lost)
 * - 70% No Effect (permanently marked Corrupted — cannot be corrupted again!)
 */
export function applyChaosStoneToSkill(
  current: SkillTreeNodeProgress,
  skill: TreeSkillDef,
  rng: () => number = Math.random
): SkillChaosCorruptionResult | null {
  if (current.corrupted || current.rank < 1) return null;
  const roll = rng() * 100;
  const previousRank = current.rank;

  if (roll < 10) {
    // 10%: Permanent Chaos Skill Modifier!
    const pool = skill.eligibleChaosMods.length > 0 ? skill.eligibleChaosMods : OFFENSE_MODS;
    const modId = pool[Math.floor(rng() * pool.length)];
    const modDef = SKILL_CHAOS_MODIFIERS[modId];
    return {
      outcome: 'new_modifier',
      skillId: skill.id,
      previousRank,
      newRank: previousRank,
      chaosModId: modId,
      updatedProgress: {
        rank: previousRank,
        corrupted: true,
        chaosModId: modId,
      },
      message: `✨ SKAŻENIE CHAOSU! ${skill.name} zyskał modyfikator: ${modDef.icon} ${modDef.name}!`,
    };
  }

  if (roll < 20) {
    // 10%: +2 Overcap Breakthrough (up to +12!)
    const newRank = Math.min(MAX_TREE_SKILL_OVERCAP_RANK, previousRank + 2);
    return {
      outcome: 'overcap_plus2',
      skillId: skill.id,
      previousRank,
      newRank,
      chaosModId: current.chaosModId ?? null,
      updatedProgress: {
        rank: newRank,
        corrupted: true,
        chaosModId: current.chaosModId ?? null,
      },
      message:
        newRank > MAX_TREE_SKILL_RANK
          ? `🔥 PRZEŁAMANIE POZIOMU! ${skill.name} przekroczył limit +10 i awansował na +${newRank}/10!`
          : `⚡ PRZEŁAMANIE (+2)! ${skill.name} awansował z +${previousRank} na +${newRank}!`,
    };
  }

  if (roll < 30) {
    // 10%: Reset Skill to 0!
    return {
      outcome: 'reset_zero',
      skillId: skill.id,
      previousRank,
      newRank: 0,
      chaosModId: null,
      updatedProgress: {
        rank: 0,
        corrupted: true,
        chaosModId: null,
      },
      message: `💥 ROZPAD CHAOSU! ${skill.name} został wyzerowany do poziomu 0!`,
    };
  }

  // 70%: No effect (permanently locked as Corrupted!)
  return {
    outcome: 'no_effect',
    skillId: skill.id,
    previousRank,
    newRank: previousRank,
    chaosModId: null,
    updatedProgress: {
      rank: previousRank,
      corrupted: true,
      chaosModId: null,
    },
    message: `💨 Kamień Chaosu pękł bez skutku — ${skill.name} został na stałe Skażony Chaosem.`,
  };
}
